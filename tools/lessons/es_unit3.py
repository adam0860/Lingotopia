L29 = lesson(
    "Whose is it? De and del",
    "la pluma de la profesora, el padre del director",
    requires=["de", "del", "familia", "amigo", "padre"],
    cards=[
        card("No apostrophe-s",
             "Spanish has no ’s. To show who owns something, or how people are related, put de between the two "
             "nouns. The order is reversed compared with English: the thing first, then the owner.",
             examples=[
                 ex("la pluma de la profesora", "the teacher’s pen", "de la profesora"),
                 ex("la esposa de mi hermano", "my brother’s wife", "de mi hermano"),
                 ex("los libros de Ana", "Ana’s books", "de Ana"),
                 ex("¿De quién es la mochila?", "Whose backpack is it?", "¿De quién"),
                 ex("Es de Pedro.", "It’s Pedro’s.", "de Pedro"),
             ]),
        card("De + el = del",
             "When de meets the article el, the two words merge into del. De la, de los and de las do not "
             "contract. Be careful: de él (“his”, “of him”) stays separate, because there él is a pronoun with "
             "an accent.",
             tables=[table(["Without contraction", "With contraction"],
                           [["de + el director", "del director"],
                            ["de + la directora", "de la directora"],
                            ["de + los alumnos", "de los alumnos"],
                            ["de + las alumnas", "de las alumnas"]],
                           say=[1])],
             examples=[ex("La esposa del profesor es ingeniera.", "The professor’s wife is an engineer.", "del profesor")]),
    ],
    exercises=[
        M("How do you say “the teacher’s pen” (a female teacher)?", "la pluma de la profesora",
          ["la profesora pluma", "la pluma de profesora", "la profesora’s pluma"], "Thing + de + owner."),
        F("la casa ___ mis padres", "de", ["del", "por", "para"], "Mis is not el, so no contraction: de mis padres.",
          tr="my parents’ house"),
        F("el libro ___ profesor", "del", ["de el", "de la", "al"], "De + el = del.", tr="the professor’s book"),
        F("la hermana ___ director", "del", ["de el", "de la", "al"], "De + el → del.", tr="the director’s sister"),
        F("la hija ___ doctora", "de la", ["del", "de el", "de lo"], "La does not contract with de.", tr="the doctor’s daughter"),
        M("How do you ask “Whose pen is it?”", "¿De quién es la pluma?", ["¿Quién es la pluma?", "¿Cuál es la pluma de?", "¿Cómo es la pluma?"],
          "De quién = whose."),
        M("How do you say “It’s Ana’s”?", "Es de Ana.", ["Es Ana’s.", "Es la Ana.", "Es el Ana."], "Ser de + name."),
        M("Which is correct?", "los amigos de mis hermanos", ["los hermanos amigos de mis", "mis hermanos’ amigos", "los de amigos mis hermanos"],
          "Thing, then de, then owner."),
        M("How do you write “of him” (his)?", "de él", ["del", "de el", "d’él"],
          "The pronoun él keeps its accent and does not merge with de. Del is only de + the article el."),
    ],
)

