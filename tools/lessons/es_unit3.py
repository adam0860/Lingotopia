L30 = lesson(
    "My, your, his: possessive adjectives",
    "mi, tu, su, nuestro, vuestro",
    requires=["mi", "tu", "su", "nuestro", "familia", "padre"],
    cards=[
        card("The possessives",
             "Possessive adjectives come before the noun. Mi, tu and su change only for number: they agree "
             "with the thing owned (mis libros). Nuestro and vuestro also change for gender.",
             tables=[table(["Owner", "Before singular", "Before plural"],
                           [["my", "mi", "mis"],
                            ["your (tú)", "tu", "tus"],
                            ["your (usted, ustedes), his, her, its, their", "su", "sus"],
                            ["our", "nuestro · nuestra", "nuestros · nuestras"],
                            ["your (vosotros, Spain)", "vuestro · vuestra", "vuestros · vuestras"]],
                           say=[1, 2])],
             examples=[
                 ex("mi hijo · mis hijos", "my son · my sons"),
                 ex("nuestra hija · nuestras hijas", "our daughter · our daughters"),
             ]),
        card("The owner does not matter",
             "The adjective agrees with what is owned, not with the owner. A woman says mi padre; two brothers "
             "say nuestra madre. Because su means his, her, your (formal) and their, you can clarify with "
             "de él, de ella, de usted, de ellos: la casa de ella.",
             examples=[
                 ex("Mi padre es ingeniero.", "My father is an engineer.", "Mi"),
                 ex("Tus hermanas son simpáticas.", "Your sisters are nice.", "Tus"),
                 ex("Su esposa trabaja en un banco.", "His, her or your wife works in a bank.", "Su"),
                 ex("Nuestros abuelos viven en Cuba.", "Our grandparents live in Cuba.", "Nuestros"),
                 ex("La casa de ella es grande.", "Her house is big.", "de ella"),
             ]),
    ],
    exercises=[
        F("Yo vivo con ___ familia.", "mi", ["mis", "mía", "mío"], "Familia is singular and I am the owner: mi.",
          tr="I live with my family."),
        F("Ella tiene tres hermanos. ___ hermanos son altos.", "Sus", ["Su", "Mis", "Tus"],
          "Hermanos is plural and the owner is she: sus.", tr="She has three brothers. Her brothers are tall."),
        F("¿Cómo se llaman ___ padres? (to a friend)", "tus", ["tu", "mis", "su"], "Padres is plural and tú: tus.",
          tr="What are your parents called?"),
        F("Nosotros amamos a ___ abuela.", "nuestra", ["nuestro", "nuestros", "mía"],
          "Abuela is feminine singular, so nuestra.", tr="We love our grandmother."),
        F("Ellos viven con ___ hijos.", "sus", ["su", "nuestro", "mía"], "Plural noun, third-person owner: sus.",
          tr="They live with their children."),
        F("Nuestros ___ trabajan en Lima.", "primos", ["prima", "casa", "tía"], "Nuestros is masculine plural.",
          tr="Our cousins work in Lima."),
        M("A woman says “my brother”. Which is correct?", "mi hermano", ["mia hermano", "mi hermana", "mío hermano"],
          "Mi does not change for the owner’s gender."),
        M("Which possessive changes for gender?", "nuestro", ["mi", "tu", "su"], "Only nuestro and vuestro."),
        M("How can you make “su casa” clearly mean “her house”?", "la casa de ella", ["la casa su", "la ella casa", "su ella casa"],
          "De ella states whose house it is."),
        M("Which is correct for “your (tú) books”?", "tus libros", ["tu libros", "tú libros", "tus libro"],
          "Libros is plural; tu has no accent."),
    ],
)

